-- PostgreSQL. Ejecutar dentro de la base de datos citas_medicas.
-- Esta migracion crea las 11 tablas del dominio. No elimina datos existentes.
CREATE TABLE roles (
    id_rol SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_rol VARCHAR(30) NOT NULL UNIQUE,
    nombre_rol VARCHAR(50) NOT NULL,
    CONSTRAINT ck_roles_codigo CHECK (codigo_rol IN ('administrador', 'recepcionista', 'medico', 'paciente'))
);

CREATE TABLE usuarios (
    id_usuario BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_rol SMALLINT NOT NULL REFERENCES roles(id_rol),
    nombres_usuario VARCHAR(80) NOT NULL,
    apellidos_usuario VARCHAR(80) NOT NULL,
    correo_usuario VARCHAR(160) NOT NULL UNIQUE,
    contrasena_hash VARCHAR(255) NOT NULL,
    usuario_activo BOOLEAN NOT NULL DEFAULT TRUE,
    version_credenciales INTEGER NOT NULL DEFAULT 1 CHECK (version_credenciales > 0),
    fecha_registro_usuario TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_usuarios_correo_normalizado CHECK (correo_usuario = lower(trim(correo_usuario)))
);
CREATE INDEX idx_usuarios_rol ON usuarios(id_rol);

CREATE TABLE pacientes (
    id_paciente BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL UNIQUE REFERENCES usuarios(id_usuario),
    cedula_identidad VARCHAR(25) NOT NULL UNIQUE,
    fecha_nacimiento DATE NOT NULL,
    telefono_paciente VARCHAR(25) NOT NULL,
    direccion_paciente VARCHAR(200) NOT NULL DEFAULT '',
    nombre_contacto_emergencia VARCHAR(120) NOT NULL DEFAULT '',
    telefono_contacto_emergencia VARCHAR(25) NOT NULL DEFAULT ''
);

CREATE TABLE historias_clinicas (
    id_historia_clinica BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL UNIQUE REFERENCES pacientes(id_paciente),
    tipo_sangre VARCHAR(5),
    alergias TEXT NOT NULL DEFAULT '',
    antecedentes_medicos TEXT NOT NULL DEFAULT '',
    fecha_apertura_historia TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_historias_tipo_sangre CHECK (tipo_sangre IN ('A+', 'A-', 'B+', 'B-', 'AB+', 'AB-', 'O+', 'O-'))
);

CREATE TABLE especialidades (
    id_especialidad BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    nombre_especialidad VARCHAR(100) NOT NULL UNIQUE,
    descripcion_especialidad VARCHAR(300) NOT NULL DEFAULT '',
    especialidad_activa BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE medicos (
    id_medico BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL UNIQUE REFERENCES usuarios(id_usuario),
    id_especialidad BIGINT NOT NULL REFERENCES especialidades(id_especialidad),
    matricula_profesional VARCHAR(40) NOT NULL UNIQUE
);
CREATE INDEX idx_medicos_especialidad ON medicos(id_especialidad);

CREATE TABLE horarios_medicos (
    id_horario_medico BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_medico BIGINT NOT NULL REFERENCES medicos(id_medico),
    fecha_atencion DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    CONSTRAINT ck_horarios_horas CHECK (hora_fin > hora_inicio),
    CONSTRAINT uq_horarios_medico_inicio UNIQUE (id_medico, fecha_atencion, hora_inicio)
);

CREATE TABLE turnos (
    id_turno BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_horario_medico BIGINT NOT NULL REFERENCES horarios_medicos(id_horario_medico),
    fecha_hora_inicio TIMESTAMP NOT NULL,
    fecha_hora_fin TIMESTAMP NOT NULL,
    turno_habilitado BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_turnos_duracion CHECK (fecha_hora_fin = fecha_hora_inicio + INTERVAL '15 minutes'),
    CONSTRAINT uq_turnos_horario_inicio UNIQUE (id_horario_medico, fecha_hora_inicio)
);

CREATE TABLE citas (
    id_cita BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL REFERENCES pacientes(id_paciente),
    id_turno BIGINT NOT NULL REFERENCES turnos(id_turno),
    estado_cita VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    motivo_cita VARCHAR(500) NOT NULL DEFAULT '',
    fecha_reserva_cita TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_citas_estado CHECK (estado_cita IN ('pendiente', 'confirmada', 'atendida', 'cancelada', 'no_asistio', 'reprogramada'))
);
CREATE UNIQUE INDEX uq_citas_turno_ocupado ON citas(id_turno) WHERE estado_cita NOT IN ('cancelada', 'reprogramada');
CREATE INDEX idx_citas_paciente ON citas(id_paciente);

CREATE TABLE consultas (
    id_consulta BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_cita BIGINT NOT NULL UNIQUE REFERENCES citas(id_cita),
    id_historia_clinica BIGINT NOT NULL REFERENCES historias_clinicas(id_historia_clinica),
    diagnostico_consulta TEXT NOT NULL,
    observaciones_consulta TEXT NOT NULL DEFAULT '',
    fecha_registro_consulta TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_consultas_historia ON consultas(id_historia_clinica);

CREATE TABLE tratamientos (
    id_tratamiento BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    id_consulta BIGINT NOT NULL REFERENCES consultas(id_consulta),
    medicamento_tratamiento VARCHAR(150) NOT NULL,
    dosis_tratamiento VARCHAR(100) NOT NULL,
    frecuencia_tratamiento VARCHAR(100) NOT NULL,
    duracion_tratamiento VARCHAR(100) NOT NULL,
    indicaciones_tratamiento TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_tratamientos_consulta ON tratamientos(id_consulta);
